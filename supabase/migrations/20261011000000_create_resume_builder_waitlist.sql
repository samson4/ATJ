create table if not exists public.resume_builder_waitlist (
  id bigint generated by default as identity primary key,
  email text not null,
  created_at timestamptz not null default now(),
  constraint resume_builder_waitlist_email_length check (char_length(email) between 3 and 320)
);

create unique index if not exists resume_builder_waitlist_email_unique
  on public.resume_builder_waitlist (lower(email));

alter table public.resume_builder_waitlist enable row level security;

comment on table public.resume_builder_waitlist is
  'Email signups requesting access to the Resume Builder beta.';
